import { readFileSync } from "node:fs"
import { gzipSync } from "node:zlib"

type SourceMap = { sources: string[]; mappings: string }
type Share = { source: string; bytes: number; kb: number }
type Slice = { line: number; start: number; end: number }

const base64 = new Map(Array.from("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/", (char, index) => [char, index]))

function decodeSegment(text: string): number[] {
  const values: number[] = []
  let value = 0
  let shift = 0
  for (const char of text) {
    const digit = base64.get(char)
    if (digit === undefined) throw Error(`Bad source map character ${char}`)
    value += (digit & 31) << shift
    if (digit & 32) {
      shift += 5
      continue
    }
    values.push(value & 1 ? -(value >>> 1) : value >>> 1)
    value = 0
    shift = 0
  }
  return values
}

const gzipKb = (text: string | Uint8Array) => gzipSync(text, { level: 9 }).byteLength / 1024

/** Generated bytes per original source, from a built file and its `.map`. A source's KB is what the file's gzip -9 size loses without that source's generated text. */
export function explain(file: string): { total: number; shares: Share[] } {
  const code = readFileSync(file, "utf8")
  const map = JSON.parse(readFileSync(`${file}.map`, "utf8")) as SourceMap
  const lines = code.split("\n")
  const slices = new Map<string, Slice[]>()
  let source = 0
  map.mappings.split(";").forEach((line, index) => {
    const text = lines[index] ?? ""
    const segments = line ? line.split(",").map(decodeSegment) : []
    let column = 0
    const starts: { column: number; source: number | undefined }[] = []
    for (const segment of segments) {
      column += segment[0] ?? 0
      if (segment.length > 1) source += segment[1] ?? 0
      starts.push({ column, source: segment.length > 1 ? source : undefined })
    }
    starts.forEach((start, position) => {
      const end = starts[position + 1]?.column ?? text.length
      const name = start.source === undefined ? "(unmapped)" : map.sources[start.source] ?? "(unknown)"
      const list = slices.get(name) ?? []
      list.push({ line: index, start: start.column, end })
      slices.set(name, list)
    })
  })
  const total = gzipKb(code)
  const without = (removed: readonly Slice[]) => {
    const byLine = Map.groupBy(removed, (slice) => slice.line)
    return lines.map((text, index) => {
      const cut = (byLine.get(index) ?? []).toSorted((a, b) => a.start - b.start)
      let kept = ""
      let at = 0
      for (const slice of cut) {
        kept += text.slice(at, slice.start)
        at = slice.end
      }
      return kept + text.slice(at)
    }).join("\n")
  }
  const shares = [...slices].map(([name, list]) => ({
    source: name.replace(/^(\.\.\/)+/, "").replace(/^.*node_modules\//, "node_modules/"),
    bytes: list.reduce((sum, slice) => sum + Buffer.byteLength(lines[slice.line]?.slice(slice.start, slice.end) ?? ""), 0),
    kb: total - gzipKb(without(list))
  })).sort((a, b) => b.kb - a.kb)
  return { total, shares }
}

if (import.meta.main) {
  const [file, limitText] = process.argv.slice(2)
  if (!file) throw Error("Usage: PP_SOURCEMAP=1 wxt build, then bun scripts/explain-bundle.ts <built file> [rows]")
  const { total, shares } = explain(file)
  const limit = Number(limitText ?? 40)
  console.log(`${file}: ${total.toFixed(2)} KB gzip -9`)
  for (const share of shares.slice(0, limit)) {
    console.log(`${share.kb.toFixed(2).padStart(7)} KB ${String(share.bytes).padStart(8)} B  ${share.source}`)
  }
}
