// THROWAWAY PROTOTYPE (ticket 15). Generates src/ui/components/glyphs.ts: the popup's first-view icons as Lucide's
// own SVG path data (ISC), drawn by Glyph.svelte. Lucide's Svelte components cost ~4 KB gzip in the first view (its
// Icon component, prop handling and one module per icon); inline path data costs ~1 KB. Lazy parts keep Lucide.
//   bun scripts/glyphs.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const names = [
  "settings",
  "chevron-down",
  "chevron-right",
  "triangle-alert",
  "info",
  "circle-check",
  "circle-alert",
  "user-round",
  "list-plus",
  "keyboard",
  "bookmark-plus",
  "list-end",
  "rectangle-ellipsis",
  "mouse-pointer-click",
  "list-music",
  "keyboard-music",
  "pause",
  "check",
  "headphones",
  "bookmark",
  "loader-circle",
];

const dir = join(import.meta.dir, "..", "node_modules", "@lucide", "svelte", "dist", "icons");
const out: string[] = [];
for (const n of names) {
  const src = readFileSync(join(dir, `${n}.svelte`), "utf8");
  const m = src.match(/const iconData = (\{.*\});/);
  if (!m) throw new Error(`no icon data in ${n}`);
  const node = JSON.parse(m[1]).node as [string, Record<string, string>][];
  const svg = node
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`)
    .join("");
  out.push(`  "${n}": '${svg}',`);
}
writeFileSync(
  join(import.meta.dir, "..", "src", "ui", "components", "glyphs.ts"),
  `// GENERATED by scripts/glyphs.ts from @lucide/svelte (ISC licence, https://lucide.dev). Do not edit by hand.
export const glyphs = {
${out.join("\n")}
} as const;
export type GlyphName = keyof typeof glyphs;
`,
);
console.log(`${names.length} glyphs`);
